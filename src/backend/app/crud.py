def update_post(db: Session, post: Post, updates: dict) -> Post:
    for key, value in updates.items():
        if hasattr(post, key):
            setattr(post, key, value)
    if updates.get("status") == "rejected":
        post.reviewed_at = func.now()
    db.commit()
    db.refresh(post)
    return post


